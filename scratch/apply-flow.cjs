const { chromium } = require('playwright');
(async () => {
  const b = await chromium.launch({ channel: 'msedge' });
  const p = await b.newPage({ viewport: { width: 1600, height: 950 } });
  const errors = [];
  p.on('pageerror', (e) => errors.push(String(e)));
  await p.goto('http://127.0.0.1:3100/dev-studio');
  await p.fill('input[type=text]', process.env.U);
  await p.fill('input[type=password]', process.env.P);
  await p.click('button[type=submit]');
  await p.waitForSelector('[role=treeitem]');
  await p.keyboard.press('Control+k');
  await p.keyboard.type('RoleList');
  await p.waitForTimeout(300);
  await p.keyboard.press('Enter');
  await p.waitForSelector('[aria-label="Page design canvas"] th[data-bos-node]');
  await p.waitForTimeout(800);
  await p.locator('[aria-label="Page design canvas"] th[data-bos-node]').first().click();
  const caption = p.locator('aside:visible label:has-text("caption") input').first();
  await caption.fill('Display Name');
  await caption.press('Tab');
  await p.waitForTimeout(1500);
  const header = await p.locator('[aria-label="Page design canvas"] th[data-bos-node]').first().textContent();
  await p.click('button:has-text("Apply")');
  await p.waitForTimeout(3000);
  const banner = await p.locator('text=Page applied and published').count();
  const err = await p.locator('text=/^Designer/').count();
  console.log(JSON.stringify({ header: header.trim(), applied: banner, errorBanner: err, errors }));
  await b.close();
})();
