$baseUri = "http://localhost:3000"
$suffix = [string](Get-Random)
$testRole = "ROLE_$suffix"
$testUser = "user_$suffix@enterprise.bos"
$testToken = "sess_sec_tok_$suffix"

Write-Host "============================================================" -ForegroundColor Cyan
Write-Host "BOS AUTHENTICATION PACKAGE (bos.auth) END-TO-END VERIFICATION" -ForegroundColor Cyan
Write-Host "============================================================" -ForegroundColor Cyan

Write-Host "`n--- 1. Testing Health Endpoint ---" -ForegroundColor Cyan
$health = Invoke-RestMethod -Uri "$baseUri/api/health" -Method Get
Write-Host "Health: $($health | ConvertTo-Json -Compress)"

Write-Host "`n--- 2. Creating Security Role ($testRole) ---" -ForegroundColor Cyan
$roleBody = @{
    code = $testRole
    name = "Enterprise Security Role $suffix"
    description = "Role generated by live automated verification suite"
} | ConvertTo-Json
$roleRes = Invoke-RestMethod -Uri "$baseUri/api/entities/sec_role" -Method Post -ContentType "application/json" -Body $roleBody
Write-Host "Role Created Successfully: $($roleRes | ConvertTo-Json -Compress)"

Write-Host "`n--- 3. Creating Security User ($testUser) ---" -ForegroundColor Cyan
$userBody = @{
    username = $testUser
    email = $testUser
    password_hash = "argon2id`$v=19`$m=65536,t=3,p=4`$salt`$hash_placeholder"
    full_name = "Automated Security Agent $suffix"
    is_active = $true
    failed_attempts = 0
} | ConvertTo-Json
$userRes = Invoke-RestMethod -Uri "$baseUri/api/entities/sec_user" -Method Post -ContentType "application/json" -Body $userBody
Write-Host "User Created Successfully: $($userRes | ConvertTo-Json -Compress)"

Write-Host "`n--- 4. Assigning Role to User (sec_user_role) ---" -ForegroundColor Cyan
$userRoleBody = @{
    username = $testUser
    role_code = $testRole
} | ConvertTo-Json
$userRoleRes = Invoke-RestMethod -Uri "$baseUri/api/entities/sec_user_role" -Method Post -ContentType "application/json" -Body $userRoleBody
Write-Host "Role Assigned Successfully: $($userRoleRes | ConvertTo-Json -Compress)"

Write-Host "`n--- 5. Issuing Session Token (sec_session_token) ---" -ForegroundColor Cyan
$tokenBody = @{
    token = $testToken
    username = $testUser
    is_revoked = $false
    ip_address = "127.0.0.1"
} | ConvertTo-Json
$tokenRes = Invoke-RestMethod -Uri "$baseUri/api/entities/sec_session_token" -Method Post -ContentType "application/json" -Body $tokenBody
Write-Host "Session Token Issued: $($tokenRes | ConvertTo-Json -Compress)"

Write-Host "`n--- 6. Querying Users via Base Query Protocol (/api/query) ---" -ForegroundColor Cyan
$queryBody = @{
    entity = "sec_user"
    select = @("username", "email", "full_name", "is_active")
    filter = @{
        username = $testUser
    }
    limit = 5
} | ConvertTo-Json
$queryRes = Invoke-RestMethod -Uri "$baseUri/api/query" -Method Post -ContentType "application/json" -Body $queryBody
Write-Host "Query Succeeded! Users returned: $($queryRes.count)"
$queryRes.data | Format-Table -Property _id, username, email, full_name, is_active

Write-Host "`n--- 7. Executing Codeunit SecAuthManager.ValidateUserRegistration ---" -ForegroundColor Cyan
$cuBody = @{
    method = "ValidateUserRegistration"
    params = @{
        username = $testUser
        email = $testUser
    }
} | ConvertTo-Json
$cuRes = Invoke-RestMethod -Uri "$baseUri/api/codeunits/SecAuthManager/run" -Method Post -ContentType "application/json" -Body $cuBody
Write-Host "Codeunit Result: $($cuRes | ConvertTo-Json -Compress)"

Write-Host "`n--- 8. Executing Codeunit SecAuthManager.CheckTokenStatus ---" -ForegroundColor Cyan
$cuBody2 = @{
    method = "CheckTokenStatus"
    params = @{
        token = $testToken
    }
} | ConvertTo-Json
$cuRes2 = Invoke-RestMethod -Uri "$baseUri/api/codeunits/SecAuthManager/run" -Method Post -ContentType "application/json" -Body $cuBody2
Write-Host "Token Check Result: $($cuRes2 | ConvertTo-Json -Compress)"

Write-Host "`n============================================================" -ForegroundColor Cyan
Write-Host "BOS AUTHENTICATION PACKAGE (bos.auth) VERIFIED 100% SUCCESS!" -ForegroundColor Cyan
Write-Host "============================================================" -ForegroundColor Cyan
